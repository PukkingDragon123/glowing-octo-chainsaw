function buildFont(name: string, table: Record<string, string>, height: number, upperOnly: boolean, fixedDigits: boolean, descent = 0): BitmapFont {
  const glyphs = new Map<string, Glyph>();
  for (const [ch, def] of Object.entries(table)) {
    let rows = def.split('/');
    while (rows.length < height) rows.push('.'.repeat(rows[0].length));
    rows = rows.slice(0, height + descent);
    const width = Math.max(...rows.map((r) => r.length));
    rows = rows.map((r) => r.padEnd(width, '.'));
    glyphs.set(ch, { w: width, rows });
  }
  if (fixedDigits) {
    const dw = Math.max(...'0123456789'.split('').map((d) => glyphs.get(d)?.w ?? 0));
    for (const d of '0123456789') {
      const g = glyphs.get(d);
      if (g && g.w < dw) {
        const pad = dw - g.w;
        const left = Math.floor(pad / 2);
        g.rows = g.rows.map((r) => '.'.repeat(left) + r + '.'.repeat(pad - left));
        g.w = dw;
      }
    }
  }
  return { name, height, descent, spacing: 1, spaceWidth: height >= 7 ? 3 : 2, glyphs, upperOnly };
}

export const FONT_BIG = buildFont('big', BIG, 7, false, true, 2);
export const FONT_TINY = buildFont('tiny', TINY, 5, true, true);

function glyphFor(font: BitmapFont, ch: string): Glyph | undefined {
  let g = font.glyphs.get(ch);
  if (!g && font.upperOnly) g = font.glyphs.get(ch.toUpperCase());
  if (!g && !font.upperOnly) g = font.glyphs.get(ch.toUpperCase()) ?? font.glyphs.get(ch.toLowerCase());
  return g;
}

export function measureText(font: BitmapFont, text: string, scale = 1, spacing = font.spacing): number {
  let w = 0;
  let first = true;
  for (const ch of text) {
    if (!first) w += spacing;
    first = false;
    if (ch === ' ') {
      w += font.spaceWidth;
      continue;
    }
    const g = glyphFor(font, ch);
    w += g ? g.w : font.spaceWidth;
  }
  return w * scale;
}

/**
 * Draw text with integer pixels. Returns the drawn width.
 * `plot` receives pixel coordinates in glyph space scaled by `scale`.
 */
export function forEachTextPixel(
  font: BitmapFont,
  text: string,
  plot: (x: number, y: number) => void,
  spacing = font.spacing,
): number {
  let cx = 0;
  let first = true;
  for (const ch of text) {
    if (!first) cx += spacing;
    first = false;
    if (ch === ' ') {
      cx += font.spaceWidth;
      continue;
    }
    const g = glyphFor(font, ch);
    if (!g) {
      cx += font.spaceWidth;
      continue;
    }
    for (let y = 0; y < g.rows.length; y++) {
      const row = g.rows[y];
      for (let x = 0; x < row.length; x++) if (row[x] === '#') plot(cx + x, y);
    }
    cx += g.w;
  }
  return cx;
}
