/**
 * Hand-drawn bitmap fonts for crisp pixel text on canvas textures.
 * Each glyph is rows of '#'/'.' separated by '/'. Glyph widths are trimmed for proportional spacing
 * (digits keep full width so prices line up).
 */

export interface Glyph {
  w: number;
  rows: string[];
}

export interface BitmapFont {
  name: string;
  /** Cap height in rows; letters like g and y hang up to `descent` rows below it. */
  height: number;
  descent: number;
  spacing: number;
  spaceWidth: number;
  glyphs: Map<string, Glyph>;
  upperOnly: boolean;
}

